// Dependency-virtualization emits (registry.yaml domain 9, R-CLI-8
// proposed): `tortureu emit hoverfly` and `tortureu emit localstack`.
//
// Neither tool is a fault injector, and this file refuses to pretend
// otherwise. Hoverfly stands in for a `class: mock` egress host and can
// carry exactly one fault verb as a response behaviour (latency, via the
// simulation's globalActions.delays). LocalStack emulates the AWS API and
// carries none at all. Every other fault in torture.yaml is reported, per
// fault, as untranslated with the reason — never dropped (R-CLI-8) — and
// the reports name the emitter that DOES translate it.
//
// Nothing here guesses an address, region, credential or response body.
// torture.yaml carries no response bodies and no AWS region, so the
// hoverfly simulation answers with an empty body and the localstack script
// fails closed on an unset AWS_REGION, in the manner protocol.go's
// noDepNote established for sysbench/memtier.
//
// VERIFICATION STATUS (performed on this host, 2026-08-08, with Docker):
//
//	VERIFIED — hoverfly: this emitter's output was written to a file and
//	  run verbatim with bash. It started spectolabs/hoverfly:v1.12.11,
//	  waited on the admin API, and imported the simulation it generated
//	  (schemaVersion v5.3, one destination-matched pair, one
//	  globalActions.delays entry with an escaped urlPattern) via
//	  `PUT /api/v2/simulation`. A request through the proxy to the mocked
//	  host then returned 200 after 2.010s — the 2000ms delay this file
//	  derives from `inject: {latency: 2s}` really applied — and a request
//	  to a host absent from the simulation returned 502.
//	VERIFIED — localstack: this emitter's output was likewise run verbatim.
//	  With AWS_REGION unset it exits non-zero with the message above and
//	  starts nothing; with AWS_REGION=eu-west-1 it started
//	  localstack/localstack:4.0, and /_localstack/health then reported
//	  exactly the one detected service ("s3": "available") with every other
//	  service "disabled", the container carrying SERVICES=s3 and
//	  AWS_DEFAULT_REGION=eu-west-1. In a separate run of the same image a
//	  real S3 bucket was created and listed through the emitted endpoint.
//	  Also verified NEGATIVELY: localstack/localstack:latest (2026.7.2)
//	  exits with code 55, "License activation failed", without a
//	  LOCALSTACK_AUTH_TOKEN — which is why the emitted script pins :4.0.
//	NOT VERIFIED — neither tool was wired to a real system under test: no
//	  compose stack was pointed at the hoverfly proxy or the localstack
//	  endpoint, so the HTTP_PROXY / AWS_ENDPOINT_URL wiring the emitted
//	  comments describe is documentation, not a tested claim.
//	NOT VERIFIED — LocalStack's Chaos API (its Pro-only fault injection).
//	  No licence was available, so this file claims nothing about it and
//	  translates no fault into it.
package emit

