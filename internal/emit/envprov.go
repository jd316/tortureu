// Environment-provisioning emits (registry.yaml domain 10, R-CLI-8
// proposed): `tortureu emit testcontainers` and `tortureu emit kind`.
//
// Neither tool injects a fault. Testcontainers brings the compose stack up
// from inside a Go test; kind creates a local Kubernetes cluster. They are
// the environment the scenario runs IN, not the scenario. So both emits
// report every fault in torture.yaml as untranslated, with the reason and
// the emitter that does translate it (`tortureu emit pumba` for a compose
// stack, `tortureu emit chaosmesh` for a cluster) — a provisioning script
// that quietly ignored the faults: block would be the silent omission
// R-CLI-8 forbids.
//
// Nothing here guesses. The compose path and service name come from
// target.compose/target.service; the host port kind publishes comes from
// target.base_url and is omitted (with the reason stated in the output)
// when base_url carries none; the testcontainers helper is emitted only
// for a repo detection reports as Go, because the helper is a Go source
// file and a Python repo cannot use it.
//
// VERIFICATION STATUS (performed on this host, 2026-08-08):
//
//	VERIFIED — kind: this emitter's output was written to a file and run
//	  verbatim with bash. It wrote the cluster config, and kind v0.32.0
//	  really created the cluster from it (16s, kindest/node v1.36.1);
//	  `kubectl cluster-info --context kind-checkout-api` — the exact
//	  command this file emits — reached the control plane, and `docker ps`
//	  showed the base_url-derived mapping live as "0.0.0.0:8080->30080/tcp".
//	  The cluster was then deleted with the same `kind delete cluster
//	  --name` this file emits.
//	VERIFIED — testcontainers: this emitter's output was compiled and RUN.
//	  With only its package clause renamed, the emitted file passed
//	  `go vet` against the real module (testcontainers-go/modules/compose
//	  v0.44.0) — so the API calls are the library's, not invented — and
//	  then `go test` on it actually brought a compose stack up through
//	  Docker and logged the mapped endpoint from PortEndpoint.
//	NOT VERIFIED — that run used a synthetic one-service compose file
//	  written for the purpose (a busybox httpd published on the base_url's
//	  port), not a real application stack. What is proven is that the
//	  emitted helper compiles, provisions, and resolves the endpoint; how
//	  it behaves against a large multi-service stack with slow health
//	  checks is untested.
//	NOT VERIFIED — nothing was deployed INTO the kind cluster: no manifest
//	  was applied, so the NodePort assumption below (that the user's
//	  Service publishes nodePort 30080) is documented, not tested. kind
//	  cannot verify it — only the user's own manifests can.
package emit

