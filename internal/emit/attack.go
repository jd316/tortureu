const attackRebalanceHeader = `#!/usr/bin/env bash
# Generated by tortureu emit rebalance. Requires: docker. Reaches the
# detected kafka broker through "--network container:<broker>" (the same
# reasoning as tortureu emit sysbench/memtier: borrow the broker's network
# namespace instead of guessing a compose network or a published port),
# driving it with rpk from the ` + attackBrokerImage + ` image — rpk speaks
# the Kafka protocol, so it also works against Apache Kafka.
#
# REBALANCE STORM: a transient consumer repeatedly joins the target consumer
# group and is killed mid-batch by "timeout", so the group rebalances on
# every join and every departure — "kill consumers mid-batch, repeatedly"
# (registry.yaml).
#
# The consumer GROUP and TOPIC are NOT in torture.yaml's schema and are NOT
# guessed — set the CHANGE_ME placeholders below to your app's real consumer
# group id and a topic that group subscribes to.
#
# VERIFIED against a live redpandadata/redpanda broker on this host: this
# exact bounded-join form joined a consumer group and left on kill, and
# repeated cycles created the group and churned its membership.
#
# at:/for: on faults are NOT scheduled here — delegate tier.
`

// attackRebalance drives a Kafka rebalance storm against the detected kafka
// broker (registry.yaml when: dep:kafka). It refuses (noDepNote) rather than
// guess a broker when none is detected, and never guesses the consumer group
// or topic (R-CLI-8 honesty over coverage).
func attackRebalance(cfg *config.Config, sys *detect.System) (string, error) {
	dep, ok := findDep(sys, "kafka")
	if !ok {
		return noDepNote("rebalance", sys, "kafka"), nil
	}
	port := attackBrokerPort(dep.Address)

	var b strings.Builder
	b.WriteString(attackRebalanceHeader)
	b.WriteString("\nGROUP=CHANGE_ME    # your app's real consumer group id\n")
	b.WriteString("TOPIC=CHANGE_ME    # a topic that group subscribes to\n")
	b.WriteString("CYCLES=20          # number of join/leave cycles (the \"storm\")\n")
	b.WriteString("HOLD=4             # seconds each transient consumer stays in the group before it is killed\n\n")
	b.WriteString("for i in $(seq 1 \"$CYCLES\"); do\n")
	fmt.Fprintf(&b, "  timeout \"$HOLD\" docker run --rm --network container:%s %s \\\n", dep.Name, attackBrokerImage)
	fmt.Fprintf(&b, "    topic consume \"$TOPIC\" -X brokers=127.0.0.1:%s -g \"$GROUP\" --offset end >/dev/null 2>&1\n", port)
	b.WriteString("  echo \"rebalance cycle $i: consumer joined $GROUP then was killed mid-batch (leave)\"\n")
	b.WriteString("done\n")
	return b.String(), nil
}

