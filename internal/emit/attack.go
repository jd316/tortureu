const attackDLQKafkaHeader = `#!/usr/bin/env bash
# Generated by tortureu emit dlq-test (kafka). Requires: docker. Reaches the
# detected kafka broker the same way tortureu emit rebalance does (see that
# tool's header), using rpk from the ` + attackBrokerImage + ` image.
#
# DLQ OVERFLOW: floods the dead-letter topic until its retention evicts the
# oldest messages — "what happens when the DLQ itself fills" (registry.yaml).
# A DLQ topic with a bounded retention.bytes silently drops its oldest dead
# letters once full, so anything that later expects to replay the whole DLQ
# loses those records.
#
# The DLQ TOPIC is NOT in torture.yaml's schema and is NOT guessed — set
# DLQ_TOPIC to your real dead-letter topic.
#
# VERIFIED against a live redpandadata/redpanda broker on this host:
# flood-producing via this form with a bounded retention.bytes drove the
# topic's log-start-offset forward (oldest messages evicted), which IS the
# overflow this models.
#
# at:/for: on faults are NOT scheduled here — delegate tier.
`

const attackDLQSQSHeader = `#!/usr/bin/env bash
# Generated by tortureu emit dlq-test (sqs). Requires: the aws CLI.
#
# DLQ OVERFLOW: SQS has no size cap, so "overflow" here means the DLQ growing
# unbounded because nothing drains it — dead letters then age out at the
# queue's retention limit (max 14 days) and are silently lost. This floods
# the DLQ so you can watch your alerting / retention behaviour.
#
# The DLQ queue URL is NOT derivable — dep:sqs is detected from the lockfile
# only, and SQS is AWS-hosted with no address in your compose — and is NOT
# guessed. Set DLQ_URL. Point --endpoint-url at LocalStack to keep this off
# real AWS.
#
# VERIFICATION STATUS: NOT verified against a live SQS/LocalStack on this
# host (none was available at authoring time). The aws sqs send-message
# flags are from the AWS CLI reference, not an executed run — verify before
# relying on it.
#
# at:/for: on faults are NOT scheduled here — delegate tier.
`

// attackDLQ floods a dead-letter destination to overflow it. It prefers a
// detected kafka broker, falls back to a detected sqs client, and refuses
// (naming both dependency types) when neither is present (registry.yaml
// when: dep:kafka|dep:sqs).
func attackDLQ(cfg *config.Config, sys *detect.System) (string, error) {
	if dep, ok := findDep(sys, "kafka"); ok {
		return attackDLQKafka(dep), nil
	}
	if _, ok := findDep(sys, "sqs"); ok {
		return attackDLQSQS(), nil
	}
	return attackDLQNoDepNote(sys), nil
}

func attackDLQKafka(dep detect.Dep) string {
	port := attackBrokerPort(dep.Address)
	var b strings.Builder
	b.WriteString(attackDLQKafkaHeader)
	b.WriteString("\nDLQ_TOPIC=CHANGE_ME    # your real dead-letter topic\n")
	b.WriteString("COUNT=1000000          # messages to flood into the DLQ\n\n")
	b.WriteString("# 1) bound the DLQ's retention so it can actually overflow (skip if already bounded):\n")
	fmt.Fprintf(&b, "docker run --rm --network container:%s %s \\\n", dep.Name, attackBrokerImage)
	fmt.Fprintf(&b, "  topic alter-config \"$DLQ_TOPIC\" -X brokers=127.0.0.1:%s --set retention.bytes=2097152\n\n", port)
	b.WriteString("# 2) flood the DLQ (oldest dead letters get evicted once retention.bytes is exceeded):\n")
	fmt.Fprintf(&b, "docker run --rm --network container:%s --entrypoint /bin/sh -e DLQ_TOPIC -e COUNT %s -c \\\n", dep.Name, attackBrokerImage)
	fmt.Fprintf(&b, "  'for i in $(seq 1 \"$COUNT\"); do echo \"dlq-overflow-$i\"; done | rpk topic produce \"$DLQ_TOPIC\" -X brokers=127.0.0.1:%s -z snappy'\n", port)
	return b.String()
}

func attackDLQSQS() string {
	var b strings.Builder
	b.WriteString(attackDLQSQSHeader)
	b.WriteString("\nDLQ_URL=CHANGE_ME               # your dead-letter queue URL\n")
	b.WriteString("ENDPOINT=http://localhost:4566  # LocalStack; remove --endpoint-url below for real AWS\n")
	b.WriteString("COUNT=100000                    # messages to flood into the DLQ\n\n")
	b.WriteString("for i in $(seq 1 \"$COUNT\"); do\n")
	b.WriteString("  aws sqs send-message --endpoint-url \"$ENDPOINT\" --queue-url \"$DLQ_URL\" --message-body \"dlq-overflow-$i\" >/dev/null\n")
	b.WriteString("done\n")
	return b.String()
}

// attackDLQNoDepNote mirrors noDepNote but names both dependency types this
// tool accepts, keeping the nil-sys ("detection failed") case distinct from
// the "no such dependency" case (R-COV-6).
func attackDLQNoDepNote(sys *detect.System) string {
	if sys == nil {
		return "# tortureu emit dlq-test: the system could not be detected, so no kafka or sqs address is known; nothing to emit.\n"
	}
	return "# tortureu emit dlq-test: no kafka or sqs dependency was detected (dep:kafka|dep:sqs); nothing to emit.\n"
}

// attackBrokerPort extracts the broker port from a detected dependency
// address, defaulting to Kafka's 9092 when none was derivable.
func attackBrokerPort(address string) string {
	if _, port := hostPort(address); port != "" {
		return port
	}
	return "9092"
}
