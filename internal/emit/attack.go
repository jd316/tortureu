// attackBrokerImage is the image whose rpk is used to reach a Kafka-compatible
// broker. rpk speaks the Kafka protocol, so it works against Apache Kafka too
// (see the package VERIFICATION STATUS for what was actually run).
const attackBrokerImage = "redpandadata/redpanda:latest"

func init() {
	// slowloris works from torture.yaml alone (it targets target.base_url);
	// rebalance and dlq-test need a real dependency address from detection
	// and must refuse rather than guess a broker/queue; fixtures needs the
	// detected language to pick a library.
	Register("slowloris", func(cfg *config.Config, _ *detect.System) (string, error) { return attackSlowloris(cfg) }, false)
	Register("rebalance", attackRebalance, true)
	Register("dlq-test", attackDLQ, true)
	Register("fixtures", attackFixtures, true)
}

// ---------------------------------------------------------------------
// slowloris — slowhttptest (registry.yaml: always)
// ---------------------------------------------------------------------

// attackSlowlorisConns is a documented default connection count. It is NOT
// derived from torture.yaml — the schema carries no such knob — so it is
// emitted with a comment saying to tune it. 500 is enough to exhaust a
// default worker/thread pool on a small service.
const attackSlowlorisConns = 500

const attackSlowlorisDefaultLen = 240 // slowhttptest's own default test length

const attackSlowlorisHeader = `#!/usr/bin/env bash
# Generated by tortureu emit slowloris. Requires: slowhttptest (v1.8.x;
# e.g. "apt-get install slowhttptest").
#
# DEFENSIVE CAPACITY SELF-TEST OF YOUR OWN SERVICE. This targets the SUT you
# declared in torture.yaml (target.base_url) and measures how your own
# server holds up under slow-request resource exhaustion (Slowloris /
# R-U-Dead-Yet / Slow Read). It is not an attack on anyone else — run it
# only against a system you operate.
#
# The connection count and interval are documented defaults, NOT derived
# from torture.yaml (its schema has no such knob) — tune them to your SUT.
#
# VERIFIED against slowhttptest 1.8.2: this flag set was run for real
# against a live server and held its connections open for the whole window.
#
# at:/for: on faults are NOT scheduled here — delegate tier (real output,
# separate timing, registry.yaml).
`

// attackSlowloris renders slowhttptest commands aimed at the operator's own
// SUT (target.base_url). Registry when: always, so it has no fault-verb gate;
// it still reports every torture.yaml fault as not translated (R-CLI-8),
// since a slow-request load tool emits request traffic, not fault injection.
func attackSlowloris(cfg *config.Config) (string, error) {
	var b strings.Builder
	b.WriteString(attackSlowlorisHeader)

	url := attackSlowlorisURL(cfg.Target.BaseURL)
	if url == "" {
		b.WriteString("\n# tortureu emit slowloris: target.base_url is not set in torture.yaml,\n")
		b.WriteString("# so there is no SUT URL to test; nothing to emit (base_url is not guessed).\n")
		return b.String(), nil
	}

	length := attackSlowlorisDefaultLen
	sizedFromLoad := false
	if total, ok := totalSeconds(cfg.Load); ok && total > 0 {
		length = total
		sizedFromLoad = true
	}

	b.WriteString("\n")
	if sizedFromLoad {
		fmt.Fprintf(&b, "# -l %d sized from load.stages' total duration.\n", length)
	} else {
		fmt.Fprintf(&b, "# -l %d is slowhttptest's default (no load.stages duration to size from).\n", length)
	}
	fmt.Fprintf(&b, "# -c %d connections is a documented default, not from torture.yaml — tune it.\n", attackSlowlorisConns)

	b.WriteString("\n# slow headers (Slowloris):\n")
	fmt.Fprintf(&b, "slowhttptest -H -c %d -r 200 -i 10 -l %d -u %s\n", attackSlowlorisConns, length, url)
	b.WriteString("\n# slow POST body (R-U-Dead-Yet):\n")
	fmt.Fprintf(&b, "slowhttptest -B -c %d -r 200 -i 10 -l %d -u %s\n", attackSlowlorisConns, length, url)
	b.WriteString("\n# slow read (Slow Read):\n")
	fmt.Fprintf(&b, "slowhttptest -X -c %d -r 200 -i 10 -l %d -k 3 -n 1 -u %s\n", attackSlowlorisConns, length, url)

	// Report every fault as not translated (R-CLI-8), reusing the shared
	// checkFaults so the verb table is the one internal/fault owns.
	faultsOut, err := checkFaults("slowloris", cfg)
	if err != nil {
		return "", err
	}
	if faultsOut != "" {
		b.WriteString("\n# faults declared in torture.yaml's faults: block (not applicable to a\n# slow-request load tool; use tortureu emit pumba/netem/iptables instead):\n")
		b.WriteString(faultsOut)
	}
	return b.String(), nil
}

// attackSlowlorisURL normalises base_url into slowhttptest's -u argument: a
// single trailing slash on the path, matching slowhttptest's own default
// ("http://localhost/"). Returns "" when base_url is empty.
func attackSlowlorisURL(baseURL string) string {
	if baseURL == "" {
		return ""
	}
	scheme, rest, ok := strings.Cut(baseURL, "://")
	if !ok {
		return baseURL
	}
	if !strings.Contains(rest, "/") {
		return scheme + "://" + rest + "/"
	}
	return baseURL
}

