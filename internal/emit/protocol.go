// Protocol-load and host-fault emit targets (SPEC.md R-CLI-8 proposed),
// added alongside the pumba/netem/iptables group in emit.go/pumba.go/
// netem.go/iptables.go.
//
// # Why this file does not touch emit.go
//
// Three agents extended `emit` concurrently against the same package. To
// avoid stepping on the other two, this file was scoped to only
// protocol.go/protocol_test.go, registering itself via init() rather than
// editing emit.go's Tools slice or Emit's switch (a shared dispatch table
// another agent's own tools also need to land in).
//
// That constraint has a real consequence, stated here rather than hidden:
// emit.go's Emit(tool, cfg) takes only a *config.Config, but two of this
// file's tools (Sysbench, Memtier — "protocol load driven by the detected
// dependency") need internal/detect's *detect.System to find the
// dependency's real address (R-DET-4) rather than guessing a port. There is
// no registry hook in emit.go for a second file to plug an extra parameter
// into Emit's existing signature without editing it. So `tortureu emit
// sysbench` does NOT work yet: EmitProtocol below is a fully real,
// independently tested entry point, but cmd/tortureu/emit.go (which this
// task also forbade touching) still only calls emit.Emit. Wiring
// `tortureu emit <tool>` up to EmitProtocol is a small, mechanical
// follow-up for whoever integrates this file — not attempted here per the
// collision-avoidance instructions ("say so and stop rather than editing
// shared code").
